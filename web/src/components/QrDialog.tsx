import { useEffect } from 'react';
import { useQuery } from '@tanstack/react-query';
import { Download, ExternalLink, Smartphone, TriangleAlert, Wifi, X } from 'lucide-react';
import type { SystemInfo } from '@flowforge/shared';
import { api } from '../lib/api';
import { CopyButton } from './CopyButton';

export const qrSrc = (text: string, size = 512, download?: string) =>
  `/api/qr?size=${size}&text=${encodeURIComponent(text)}${download ? `&download=${encodeURIComponent(download)}` : ''}`;

export function useSystemInfo() {
  return useQuery({ queryKey: ['system', 'info'], queryFn: () => api<SystemInfo>('/system/info'), staleTime: 60_000 });
}

/** Tells whether a phone can open the public URL, and what to do when it cannot. */
export function ReachHint({ info }: { info?: SystemInfo }) {
  if (!info) return null;
  if (info.publicUrlSource === 'localhost') {
    return (
      <p className="flex items-start gap-1.5 text-[12px] text-warning" data-testid="reach-hint" data-source="localhost">
        <TriangleAlert size={13} className="mt-0.5 shrink-0" />
        <span>
          This address only works on this computer. Connect it to Wi-Fi and restart FlowForge, or set <code className="rounded bg-panel-2 px-1">PUBLIC_URL</code> in <code className="rounded bg-panel-2 px-1">.env</code> (see README: "Open FlowForge from a phone").
        </span>
      </p>
    );
  }
  if (info.publicUrlSource === 'lan') {
    return (
      <p className="flex items-start gap-1.5 text-[12px] text-subtle" data-testid="reach-hint" data-source="lan">
        <Wifi size={13} className="mt-0.5 shrink-0" />
        <span>
          Your phone must be on the <b className="font-medium text-muted">same Wi-Fi</b> as this computer. Page does not load? Allow port {info.port} in the firewall, or use a Cloudflare tunnel (README: "Open FlowForge from a phone").
        </span>
      </p>
    );
  }
  return (
    <p className="flex items-start gap-1.5 text-[12px] text-subtle" data-testid="reach-hint" data-source="env">
      <Smartphone size={13} className="mt-0.5 shrink-0" /> Public address from PUBLIC_URL: it works from any network.
    </p>
  );
}

/** Big QR code of a URL (generated by the local server) with copy, download and open actions. */
export function QrDialog({ url, title, openHref, fileName = 'form-qr', note, onClose }: { url: string; title: string; openHref?: string; fileName?: string; note?: string; onClose(): void }) {
  const info = useSystemInfo();
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.key === 'Escape') {
        e.stopPropagation();
        e.preventDefault();
        onClose();
      }
    };
    window.addEventListener('keydown', onKey, true);
    return () => window.removeEventListener('keydown', onKey, true);
  }, [onClose]);
  return (
    <div className="fixed inset-0 z-[60] flex items-center justify-center bg-black/70 backdrop-blur-sm" onMouseDown={(e) => e.target === e.currentTarget && onClose()}>
      <div className="flex max-h-[94vh] w-[440px] max-w-[94vw] animate-fade-in flex-col gap-4 overflow-y-auto rounded-2xl border border-line-strong bg-panel p-6 shadow-2xl" role="dialog" aria-label="QR code" data-testid="qr-dialog">
        <div className="flex items-start gap-3">
          <div className="min-w-0 flex-1">
            <h2 className="truncate text-[16px] font-semibold">{title}</h2>
            <p className="text-[12.5px] text-muted">Scan with the camera of your phone.</p>
          </div>
          <button type="button" onClick={onClose} title="Close (Esc)" className="rounded p-1.5 text-subtle hover:bg-panel-3 hover:text-fg" data-testid="qr-close">
            <X size={16} />
          </button>
        </div>
        <div className="mx-auto rounded-2xl bg-white p-3 shadow-lg">
          <img src={qrSrc(url, 720)} alt={`QR code for ${url}`} width={320} height={320} className="block size-[min(320px,60vw)]" data-testid="qr-image" />
        </div>
        <div className="flex items-center gap-1.5 rounded-md border border-line bg-panel-2 px-2.5 py-2">
          <code className="min-w-0 flex-1 break-all font-mono text-[12.5px]" data-testid="qr-url">
            {url}
          </code>
          <CopyButton text={url} testId="qr-copy" />
        </div>
        {note && <p className="text-[12px] text-subtle">{note}</p>}
        <ReachHint info={info.data} />
        <div className="flex flex-wrap gap-2">
          <a
            href={qrSrc(url, 1024, fileName)}
            download={`${fileName}.png`}
            data-testid="qr-download"
            className="inline-flex h-9 flex-1 items-center justify-center gap-2 rounded-md border border-line-strong bg-panel-3 px-4 text-sm font-medium hover:bg-line-strong/60"
          >
            <Download size={15} /> Download PNG
          </a>
          <a
            href={openHref ?? url}
            target="_blank"
            rel="noreferrer"
            data-testid="qr-open"
            className="inline-flex h-9 flex-1 items-center justify-center gap-2 rounded-md bg-accent px-4 text-sm font-medium text-white hover:bg-accent-hover"
          >
            <ExternalLink size={15} /> Open
          </a>
        </div>
      </div>
    </div>
  );
}
